def strip_lang_prefix(tag: str) -> str:
    """Strip an Open Beauty Facts `<lang>:` prefix such as `xx:` or `en:`."""
    cleaned = tag.strip().lower()
    return _LANG_PREFIX_RE.sub("", cleaned)


def fold_unicode(text: str) -> str:
    """Normalize Unicode NFKD, remove diacritic combining marks, and lowercase."""
    decomposed = unicodedata.normalize("NFKD", text)
    stripped = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    return stripped.lower().strip()


def canonical_brand_slug(name: str) -> str:
    """Compute the deterministic canonical slug for a Glow and Glare brand name."""
    folded = fold_unicode(strip_lang_prefix(name))
    folded = folded.replace("&", " and ")
    folded = folded.replace("+", " plus ")
    folded = _COLLAPSE_PUNCT_RE.sub("", folded)
    slug = _NON_ALNUM_RE.sub("-", folded).strip("-")
    return slug


def spaced_brand_slug(name: str) -> str:
    """Compute the punctuation-separated slug form (e.g. `l-oreal`, `e-l-f`, `kiehl-s`)."""
    folded = fold_unicode(strip_lang_prefix(name))
    folded = folded.replace("&", " and ")
    slug = _NON_ALNUM_RE.sub("-", folded).strip("-")
    return slug


def compact_brand_key(name: str) -> str:
    """Compute an alphanumeric-only compact key (e.g. `hudabeauty`, `olehenriksen`)."""
    folded = fold_unicode(strip_lang_prefix(name))
    folded = folded.replace("&", "and")
    return _NON_ALNUM_RE.sub("", folded)


def brand_slug_variants(name: str) -> set[str]:
    """Return all normalized slug forms (collapsed, spaced, no-plus) for matching."""
    folded = fold_unicode(strip_lang_prefix(name))
    variants: set[str] = set()
    for base in (folded, folded.replace("&", " and "), folded.replace("&", " ")):
        c_slug = _NON_ALNUM_RE.sub(
            "-", _COLLAPSE_PUNCT_RE.sub("", base.replace("+", " plus "))
        ).strip("-")
        s_slug = _NON_ALNUM_RE.sub("-", base).strip("-")
        no_plus = _NON_ALNUM_RE.sub("-", _COLLAPSE_PUNCT_RE.sub("", base.replace("+", ""))).strip(
            "-"
        )
        for cand in (c_slug, s_slug, no_plus):
            if cand:
                variants.add(cand)
    return variants


def apply_curated_metadata(entry: BrandSeedEntry) -> BrandSeedEntry:
    """Enrich a raw extracted `BrandSeedEntry` with curated aliases, risk tiers, and alias links."""
    override = CURATED_BRAND_OVERRIDES.get(entry.slug, {})
    aliases: list[str] = [entry.display_name]
    for extra in override.get("aliases", []):  # type: ignore[union-attr]
        if isinstance(extra, str) and extra not in aliases:
            aliases.append(extra)

    risk_tier: RiskTier = override.get("risk_tier", entry.risk_tier)  # type: ignore[assignment]
    alias_of: str | None = override.get("alias_of", entry.alias_of)  # type: ignore[assignment]
    is_store_own_brand: bool = bool(override.get("is_store_own_brand", entry.is_store_own_brand))
    req_pos = list(override.get("required_positive_keywords", entry.required_positive_keywords))  # type: ignore[arg-type]
    neg_kw = list(override.get("negative_keywords", entry.negative_keywords))  # type: ignore[arg-type]
    blocked = list(override.get("blocked_brand_tags", entry.blocked_brand_tags))  # type: ignore[arg-type]

    return entry.model_copy(
        update={
            "risk_tier": risk_tier,
            "alias_of": alias_of,
            "is_store_own_brand": is_store_own_brand,
            "aliases": aliases,
            "required_positive_keywords": req_pos,
            "negative_keywords": neg_kw,
            "blocked_brand_tags": blocked,
        }
    )


class BrandRegistry:
    """In-memory indexed registry of all Glow and Glare brand entities and aliases."""

    def __init__(self, entries: Iterable[BrandSeedEntry]) -> None:
        self.entries: list[BrandSeedEntry] = list(entries)
        self.by_slug: dict[str, BrandSeedEntry] = {e.slug: e for e in self.entries}

        # Slug variant -> canonical target slug (resolving alias_of links)
        self.variant_to_canonical: dict[str, str] = {}
        # Compact key (len >= 5 to avoid short-word collisions) -> canonical target slug
        self.compact_to_canonical: dict[str, str] = {}
        # Blocked brand tag variants -> set of brand slugs that must reject them
        self.blocked_by_slug: dict[str, set[str]] = {}
        # Variant strings per canonical slug (for title-prefix fallback)
        self.canonical_aliases: dict[str, list[str]] = {}

        for entry in self.entries:
            target_slug = self.resolve_canonical_slug(entry.slug)
            if entry.is_store_own_brand:
                continue
            target_entry = self.by_slug.get(target_slug, entry)
            all_names = [entry.display_name, *entry.aliases]
            alias_bucket = self.canonical_aliases.setdefault(target_slug, [])
            for raw_name in all_names:
                if raw_name not in alias_bucket:
                    alias_bucket.append(raw_name)
                for variant in brand_slug_variants(raw_name):
                    # Prefer the more specific / canonical owner if two entries mention a variant
                    if variant not in self.variant_to_canonical or target_entry.alias_of is None:
                        self.variant_to_canonical[variant] = target_slug
                comp = compact_brand_key(raw_name)
                if len(comp) >= 5 and comp not in self.compact_to_canonical:
                    self.compact_to_canonical[comp] = target_slug

            blocked_set = self.blocked_by_slug.setdefault(target_slug, set())
            for btag in entry.blocked_brand_tags:
                blocked_set.update(brand_slug_variants(btag))

    @classmethod
    def from_entries(cls, entries: Iterable[BrandSeedEntry]) -> BrandRegistry:
        """Construct a `BrandRegistry` from `BrandSeedEntry` records."""
        return cls(entries)

    def resolve_canonical_slug(self, slug: str) -> str:
        """Follow `alias_of` links to the canonical brand slug."""
        seen: set[str] = set()
        curr = slug
        while curr in self.by_slug and self.by_slug[curr].alias_of:
            if curr in seen:
                break
            seen.add(curr)
            next_slug = self.by_slug[curr].alias_of
            if next_slug is None:
                break
            curr = next_slug
        return curr

    def get_entry(self, slug: str) -> BrandSeedEntry | None:
        """Return the `BrandSeedEntry` for an exact slug."""
        return self.by_slug.get(slug)

    def get_canonical_entry(self, slug: str) -> BrandSeedEntry | None:
        """Return the canonical `BrandSeedEntry` after resolving `alias_of`."""
        return self.by_slug.get(self.resolve_canonical_slug(slug))

    @property
    def total_vendor_entries(self) -> int:
        return len(self.entries)

    @property
    def distinct_brand_entities(self) -> int:
        return sum(1 for e in self.entries if e.alias_of is None)

    @property
    def external_brand_entities(self) -> int:
        return sum(1 for e in self.entries if e.alias_of is None and not e.is_store_own_brand)

    @property
    def most_loved_count(self) -> int:
        return sum(1 for e in self.entries if e.is_most_loved)

    def resolve_parent_subbrand(self, slug_a: str, slug_b: str) -> str | None:
        """If one slug is a known parent/retailer of the other, return the specific sub-brand."""
        ca = self.resolve_canonical_slug(slug_a)
        cb = self.resolve_canonical_slug(slug_b)
        if ca == cb:
            return ca
        if cb in PARENT_SUBBRAND_GROUPS.get(ca, frozenset()):
            return cb
        if ca in PARENT_SUBBRAND_GROUPS.get(cb, frozenset()):
            return ca
        return None
